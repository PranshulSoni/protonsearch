const { chromium } = await import('playwright');
import { writeFileSync } from "node:fs";
const OUT = "C:/Users/Pranshul/Documents/Projects/protonsearch/docs/qa/g8-verify-round2";
const b = await chromium.connectOverCDP('http://127.0.0.1:9223');
const pages=[]; for (const c of b.contexts()) for (const p of c.pages()) pages.push(p);
const kinds=[]; for (const p of pages) { try { kinds.push(await p.evaluate(()=>document.documentElement.dataset.window)); } catch { kinds.push(null); } }
const main = pages[kinds.indexOf('main')]; const island = pages[kinds.indexOf('island')];
const st = await main.evaluate(()=>window.__TAURI_INTERNALS__.invoke('get_status'));
const rows = await main.evaluate(async ()=>{ const r=await window.__TAURI_INTERNALS__.invoke('search',{req:{requestId:93001,query:'',scope:'clipboard',filters:{},limit:20}}); return r.results.map(x=>({id:x.id,title:x.title,hasThumb:!!x.meta?.thumbnailDataUrl,thumbLen:(x.meta?.thumbnailDataUrl||'').length,w:x.meta?.imageWidth,h:x.meta?.imageHeight,mime:x.meta?.mime})); });
await main.evaluate(()=>window.__TAURI_INTERNALS__.invoke('show_island'));
await new Promise(r=>setTimeout(r,900));
const dots = island.locator("[data-page], .pageDot, [aria-label^='Go to']");
await dots.nth(2).click({timeout:2500}).catch(()=>{});
await new Promise(r=>setTimeout(r,800));
await island.locator('button',{hasText:'Images'}).first().click({timeout:2000}).catch(()=>{});
await new Promise(r=>setTimeout(r,800));
const dom = await island.evaluate(()=>({body:document.body.innerText.slice(0,700),imgs:[...document.querySelectorAll('img')].map(i=>({w:i.width,h:i.height,src:(i.getAttribute('src')||'').slice(0,30)})).slice(0,8)}));
await island.screenshot({path:OUT+"/p0-2-island-images.png"});
writeFileSync(OUT+"/p0-2-evidence.json",JSON.stringify({capturedAt:new Date().toISOString(),clipboard:st.sources?.find(s=>s.id==='clipboard'),rows,dom},null,2));
console.log(JSON.stringify({clip:st.sources?.find(s=>s.id==='clipboard'),rows,dom},null,1).slice(0,5000));
await main.evaluate(()=>window.__TAURI_INTERNALS__.invoke('hide_island'));
await b.close();
